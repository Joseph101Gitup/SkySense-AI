"""
Django Admin Configuration for SKYsense AI.
Provides rich inspection, filtering, and visualization of Prediction records.
"""

from django.contrib import admin
from django.utils.html import format_html
from .models import Prediction, SourceType, RainfallClass


@admin.register(Prediction)
class PredictionAdmin(admin.ModelAdmin):
    """
    Admin interface for managing and auditing Prediction records with image previews,
    color-coded rainfall category badges, and telemetry breakdowns.
    """
    list_display = (
        'thumbnail_display',
        'original_filename',
        'predicted_class_badge',
        'confidence_display',
        'source_badge',
        'latency_display',
        'model_version',
        'created_at',
    )
    list_filter = (
        'predicted_class',
        'source_type',
        'model_version',
        'risk_level',
        ('created_at', admin.DateFieldListFilter),
    )
    search_fields = (
        'original_filename',
        'user_notes',
        'device_id',
        'id',
        'meteorological_context',
    )
    ordering = ('-created_at',)
    readonly_fields = (
        'id',
        'created_at',
        'thumbnail_preview',
        'confidence',
        'low_to_medium_probability',
        'medium_to_heavy_probability',
        'no_to_low_probability',
        'processing_time',
        'model_version',
    )

    fieldsets = (
        ('Specimen & Classification Result', {
            'fields': (
                'image',
                'thumbnail_preview',
                'original_filename',
                ('predicted_class', 'confidence'),
                ('model_version', 'processing_time'),
            )
        }),
        ('Softmax Probability Distribution', {
            'fields': (
                'low_to_medium_probability',
                'medium_to_heavy_probability',
                'no_to_low_probability',
            ),
            'classes': ('collapse',),
            'description': 'Normalized class probabilities generated by Xception CNN output layer.'
        }),
        ('Ingestion Channel & IoT Telemetry (Optional)', {
            'fields': (
                'source_type',
                'device_id',
                ('latitude', 'longitude'),
                ('temperature', 'humidity'),
            ),
            'description': 'Ingestion origin and future IoT hardware edge sensor telemetry.'
        }),
        ('Meteorological Context & Notes', {
            'fields': (
                ('risk_level', 'rain_probability_range'),
                'meteorological_context',
                'advisory_action',
                'user_notes',
            )
        }),
        ('Database Provenance', {
            'fields': ('id', 'created_at'),
            'classes': ('collapse',)
        }),
    )

    @admin.display(description="Specimen")
    def thumbnail_display(self, obj):
        if obj.image:
            return format_html(
                '<img src="{}" style="width: 44px; height: 44px; object-fit: cover; border-radius: 6px; border: 1px solid #334155;" />',
                obj.image.url
            )
        return "-"

    @admin.display(description="Specimen Preview")
    def thumbnail_preview(self, obj):
        if obj.image:
            return format_html(
                '<div style="margin: 8px 0;"><img src="{}" style="max-width: 256px; max-height: 256px; border-radius: 8px; border: 1px solid #475569;" /><p style="font-size: 11px; color: #64748b; margin-top: 4px;">Rescaled to 256 &times; 256 RGB for inference</p></div>',
                obj.image.url
            )
        return "(No image available)"

    @admin.display(description="Predicted Class", ordering="predicted_class")
    def predicted_class_badge(self, obj):
        color_styles = {
            RainfallClass.LOW_TO_MEDIUM: "background-color: #78350f; color: #fde68a; border: 1px solid #d97706;",
            RainfallClass.MEDIUM_TO_HEAVY: "background-color: #881337; color: #fecdd3; border: 1px solid #e11d48;",
            RainfallClass.NO_TO_LOW: "background-color: #064e3b; color: #a7f3d0; border: 1px solid #059669;",
        }
        style = color_styles.get(obj.predicted_class, "background-color: #1e293b; color: #cbd5e1;")
        return format_html(
            '<span style="display: inline-block; padding: 3px 8px; border-radius: 9999px; font-size: 11px; font-weight: 600; {}">{}</span>',
            style,
            obj.display_name
        )

    @admin.display(description="Confidence", ordering="confidence")
    def confidence_display(self, obj):
        pct = obj.confidence_pct
        color = "#38bdf8" if pct >= 70 else ("#fbbf24" if pct >= 50 else "#f87171")
        return format_html(
            '<span style="font-family: monospace; font-weight: bold; color: {};">{}%</span>',
            color,
            pct
        )

    @admin.display(description="Source", ordering="source_type")
    def source_badge(self, obj):
        styles = {
            SourceType.WEB_UPLOAD: "background-color: #0f172a; color: #38bdf8; border: 1px solid #0284c7;",
            SourceType.IOT_DEVICE: "background-color: #3b0764; color: #e9d5ff; border: 1px solid #9333ea;",
            SourceType.API: "background-color: #172554; color: #93c5fd; border: 1px solid #2563eb;",
        }
        style = styles.get(obj.source_type, "background-color: #1e293b; color: #cbd5e1;")
        return format_html(
            '<span style="display: inline-block; padding: 2px 6px; border-radius: 4px; font-size: 10px; font-family: monospace; font-weight: bold; {}">{}</span>',
            style,
            obj.source_type
        )

    @admin.display(description="Latency", ordering="processing_time")
    def latency_display(self, obj):
        return format_html(
            '<span style="font-family: monospace; color: #94a3b8;">{} ms</span>',
            obj.latency_ms
        )
